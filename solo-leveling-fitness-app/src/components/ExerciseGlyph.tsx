export function ExerciseGlyph({
  glyph,
  size = 62,
  done = false,
  tone,
}: {
  glyph: GlyphKey;
  size?: number;
  done?: boolean;
  tone?: string;
}) {
  const pose = POSES[glyph] ?? POSES.pushup;
  const color = tone ?? (done ? "#8ff0ff" : "#3fd2ff");
  return (
    <svg
      width={size}
      height={size * 0.75}
      viewBox="0 0 68 52"
      fill="none"
      stroke={color}
      strokeWidth={done ? 2.6 : 1.9}
      strokeLinecap="square"
      style={{
        filter: `drop-shadow(0 0 5px ${color}aa)`,
        opacity: done ? 1 : 0.82,
        transition: "all 200ms ease",
      }}
    >
      {pose.bars?.map((d, i) => (
        <path key={`b${i}`} d={`M${d}`} strokeDasharray="3 3" opacity={0.55} />
      ))}
      {pose.lines.map((d, i) => (
        <path key={`l${i}`} d={`M${d}`} />
      ))}
      {pose.dots?.map(([x, y], i) => (
        <circle key={`d${i}`} cx={x} cy={y} r={1.4} fill={color} stroke="none" />
      ))}
      {pose.head ? (
        <circle cx={pose.head[0]} cy={pose.head[1]} r={4.2} fill="#01030a" stroke={color} />
      ) : null}
    </svg>
  );
}
